const notes: Record<Locale, string[]> = {
    en: ['Bergamot', 'Sandalwood', 'Rose', 'Oud', 'Vetiver', 'Jasmine', 'Amber', 'Neroli'],
    bn: ['বার্গামট', 'চন্দন', 'গোলাপ', 'উদ', 'ভেটিভার', 'জেসমিন', 'অ্যাম্বার', 'নেরোলি'],
};

export type MessageKey = keyof typeof en;

export function normalizeLocale(locale: string | undefined): Locale {
    return locale === 'en' ? 'en' : 'bn';
}

export function translate(locale: string | undefined, key: MessageKey): string {
    const pack = normalizeLocale(locale) === 'bn' ? bn : en;

    return pack[key];
}

export function term(locale: string | undefined, value: string): string {
    return families[normalizeLocale(locale)][value] ?? value;
}

export function noteLine(locale: string | undefined): string[] {
    return notes[normalizeLocale(locale)];
}

export function perfumeNames(
    locale: string | undefined,
    name: string | null,
    nameBn: string | null,
): { primary: string; secondary: string | null } {
    const english = name ?? '';
    const bangla = nameBn?.trim() ? nameBn : null;

    if (normalizeLocale(locale) === 'bn' && bangla) {
        return { primary: bangla, secondary: english || null };
    }

    return { primary: english, secondary: bangla };
}
